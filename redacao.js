  function analiseAuto(texto){
    const t = texto.toLowerCase();
    const palavras = (texto.trim().match(/\S+/g)||[]).length;
    const paragrafos = texto.trim() ? texto.trim().split(/\n\s*\n|\n/).filter(x=>x.trim().length>0).length : 0;
    const linhasEst = Math.ceil(texto.length/70);
    const conectivos = ["portanto","entretanto","contudo","todavia","ademais","além disso","por conseguinte","dessa forma","nesse sentido","em contrapartida","por outro lado"," primeiramente"," em segundo","por fim","conclui-se"];
    const foundConec = conectivos.filter(c=>t.includes(c.trim()));
    const propostaKeys = ["é necessário","é preciso","cabe ao","cumpre","deve-se","devem","política pública","projeto","programa","fiscalizar","investir","garantir","promover","medida","intervenção","ministério","governo","escola deve","família deve","mídia deve"];
    const foundProp = propostaKeys.filter(c=>t.includes(c));
    const repertorioKeys = ["segundo","conforme","dados","ibge","constituição","art.","filósofo","sociólogo","durkheim","foucault","bauman","djamila","freire","sartre","onu","oms","ipea","lei nº","de acordo"];
    const foundRep = repertorioKeys.filter(c=>t.includes(c));
    const temDH = /direitos humanos|dignidade|respeit|igualdade|inclus/i.test(texto);
    return {palavras, paragrafos, linhasEst, foundConec, foundProp, foundRep, temDH};
  }

